"""CI jobs from one definition, rendered for GitHub Actions and GitLab CI (R27, H15/H23).

A definition says what a job does (a POSIX shell script that only calls `camaron`), when (pull request) and whether
it needs AI. Where it runs is project config, `ci:` in workspace.yaml: `target` local (hosted runners for the jobs
that need no AI) or self-hosted (`runner_labels` for GitHub `runs-on`, `runner_tags` for GitLab `tags`)."""
from __future__ import annotations

from .common import VERSIONS
from . import docs

KIT_REPO = "https://github.com/iandelu/camarones-documenter.git"

# The job's script after the forge has checked the service repo out: $SRC is that checkout, $NAME its name in
# workspace.yaml, $DOCS_BASE the PR's base. It builds the workspace layout the kit expects (cam-docs next to the repo).
FRESH_SCRIPT = r'''set -eu
if [ -z "${DOCS_REPO_URL:-}" ] || [ -z "${DOCS_READ_TOKEN:-}" ]; then
  echo "docs-fresh: DOCS_REPO_URL or DOCS_READ_TOKEN is not set (pull/merge requests from forks get no secrets): skipped."
  exit 0
fi
W="$(mktemp -d)"
ln -s "$SRC" "$W/$NAME"
AUTH="$(printf '%s:%s' "$DOCS_CLONE_USER" "$DOCS_READ_TOKEN" | base64 | tr -d '\n')"
git -c "http.extraHeader=Authorization: Basic $AUTH" clone -q --depth 1 "$DOCS_REPO_URL" "$W/cam-docs"
git clone -q --depth 1 --branch "$CAMARONES_KIT_REF" "$CAMARONES_KIT_REPO" "$W/.kit"
CAMARONES_ROOT="$W/cam-docs" CAMARONES_GLOBAL=1 uv run --quiet --script "$W/.kit/.camarones/camarones.py" \
  pr fresh "$NAME" --base "$DOCS_BASE" --post --lang "${DOCS_LANG:-en}" || echo "docs-fresh: could not check the docs."
'''

PR_FRESH = {
    "id": "docs-fresh",
    "title": "Docs affected by this PR (no AI)",
    "ai": False,
    "script": FRESH_SCRIPT,
    "doc": [
        "Comments on each pull request which documentation pages its code changes leave out of date. No AI, no API key;",
        "it warns and never blocks the merge.",
    ],
}


def config() -> dict:
    ci = (docs.workspace().get("ci") or {}) if docs.WS_FILE.exists() else {}
    return {"target": ci.get("target", "local"), "runner_labels": list(ci.get("runner_labels") or ["self-hosted"]),
            "runner_tags": list(ci.get("runner_tags") or []), "kit_repo": ci.get("kit_repo", KIT_REPO),
            "kit_ref": ci.get("kit_ref", f"v{VERSIONS['kit']}"), "propose_label": ci.get("propose_label", "docs:update")}


def _indent(text: str, n: int) -> str:
    pad = " " * n
    return "\n".join(pad + line if line else "" for line in text.rstrip("\n").splitlines())


def github(defn: dict, cfg: dict) -> str:
    runs_on = f"[{', '.join(cfg['runner_labels'])}]" if cfg["target"] == "self-hosted" else "ubuntu-latest"
    head = "\n".join(f"# {l}" for l in defn["doc"])
    return f"""# Camarón — {defn['title']}. Generated by `camaron ci github`: edit the definition, not this file.
{head}
# Copy to .github/workflows/{defn['id']}.yml in EACH service repo.
# Variables: DOCS_REPO_URL (https URL of the cam-docs repo); optional DOCS_REPO_NAME (this repo's name in
# workspace.yaml, default: the repository name), DOCS_LANG (en|es). Secret: DOCS_READ_TOKEN (read access to cam-docs).
name: {defn['id']}
on:
  pull_request:
permissions: {{ contents: read, pull-requests: write }}
jobs:
  {defn['id']}:
    runs-on: {runs_on}
    env:
      CAMARONES_KIT_REPO: {cfg['kit_repo']}
      CAMARONES_KIT_REF: {cfg['kit_ref']}
      DOCS_REPO_URL: ${{{{ vars.DOCS_REPO_URL }}}}
      DOCS_LANG: ${{{{ vars.DOCS_LANG }}}}
      DOCS_READ_TOKEN: ${{{{ secrets.DOCS_READ_TOKEN }}}}
      DOCS_CLONE_USER: x-access-token
      GITHUB_TOKEN: ${{{{ github.token }}}}
      PR_NUMBER: ${{{{ github.event.pull_request.number }}}}
      NAME: ${{{{ vars.DOCS_REPO_NAME || github.event.repository.name }}}}
      DOCS_BASE: origin/${{{{ github.base_ref }}}}
    steps:
      - uses: actions/checkout@v4
        with: {{ fetch-depth: 0 }}
      - uses: astral-sh/setup-uv@v6
      - name: {defn['title']}
        run: |
          SRC="$GITHUB_WORKSPACE"
{_indent(defn['script'], 10)}
"""


def gitlab(defn: dict, cfg: dict) -> str:
    tags = (f"\n  tags: [{', '.join(cfg['runner_tags'])}]" if cfg["target"] == "self-hosted" and cfg["runner_tags"]
            else "")
    head = "\n".join(f"# {l}" for l in defn["doc"])
    script = "SRC=\"$CI_PROJECT_DIR\"\nNAME=\"${DOCS_REPO_NAME:-$CI_PROJECT_NAME}\"\n" + defn["script"]
    return f"""# Camarón — {defn['title']}. Generated by `camaron ci gitlab`: edit the definition, not this file.
{head}
# In EACH service repo: include this file from the cam-docs project, or copy the job into .gitlab-ci.yml.
# Variables: DOCS_REPO_URL (https URL of the cam-docs project), DOCS_READ_TOKEN (masked: read_repository on cam-docs),
# DOCS_BOT_TOKEN (masked: api on this repo, to comment on the merge request); optional DOCS_REPO_NAME, DOCS_LANG.
# Runs in the `test` stage: add it to `stages:` if this repo lists its own.

{defn['id'].replace('-', ':', 1)}:
  image: ghcr.io/astral-sh/uv:{cfg.get('uv', VERSIONS['uv'])}-python3.12-bookworm
  stage: test{tags}
  rules:
    - if: '$CI_PIPELINE_SOURCE == "merge_request_event"'
  allow_failure: true
  variables:
    GIT_DEPTH: "0"
    CAMARONES_KIT_REPO: "{cfg['kit_repo']}"
    CAMARONES_KIT_REF: "{cfg['kit_ref']}"
    DOCS_CLONE_USER: "oauth2"
    DOCS_BASE: "$CI_MERGE_REQUEST_DIFF_BASE_SHA"
  script:
    - |
{_indent(script, 6)}
"""


RENDER = {"github": github, "gitlab": gitlab}
FILES = {"github": "docs-fresh.github.yml", "gitlab": "docs-fresh.gitlab-ci.yml"}


def render(forge: str, defn: dict = PR_FRESH, cfg: dict | None = None) -> str:
    return RENDER[forge](defn, cfg or config())


# ---------- docs-propose: AI, self-hosted runners only (R31) ----------
PROPOSE_SCRIPT = r'''set -eu
if [ -z "${DOCS_REPO_URL:-}" ] || [ -z "${DOCS_WRITE_TOKEN:-}" ]; then
  echo "docs-propose: DOCS_REPO_URL or DOCS_WRITE_TOKEN is not set: skipped."
  exit 0
fi
W="$(mktemp -d)"
ln -s "$SRC" "$W/$NAME"
git -C "$SRC" update-ref "refs/camaron/pr/head" HEAD
AUTH="$(printf '%s:%s' "$DOCS_CLONE_USER" "$DOCS_WRITE_TOKEN" | base64 | tr -d '\n')"
# the token lives in this step's environment only, never in the runner's git config
export GIT_CONFIG_COUNT=1 GIT_CONFIG_KEY_0=http.extraHeader GIT_CONFIG_VALUE_0="Authorization: Basic $AUTH"
git clone -q "$DOCS_REPO_URL" "$W/cam-docs"
git clone -q --depth 1 --branch "$CAMARONES_KIT_REF" "$CAMARONES_KIT_REPO" "$W/.kit"
CAMARONES_ROOT="$W/cam-docs" CAMARONES_GLOBAL=1 uv run --quiet --script "$W/.kit/.camarones/camarones.py" \
  pr propose "$PR_URL" --ref refs/camaron/pr/head --base "$DOCS_BASE" --comment --preview --lang "${DOCS_LANG:-en}"
mkdir -p "$SRC/.docs-preview" && cp -R "$W/cam-docs/.camarones/.cache/previews/." "$SRC/.docs-preview/" 2>/dev/null || true
'''

PR_PROPOSE = {
    "id": "docs-propose",
    "title": "Docs proposal for a labelled PR (AI, self-hosted runner)",
    "ai": True,
    "label": "docs:update",
    "script": PROPOSE_SCRIPT,
    "doc": [
        "When a project member labels a pull request (`docs:update` unless ci.propose_label says otherwise), an agent on",
        "YOUR runner updates the pages it leaves",
        "out of date and opens a cam-docs PR. The runner needs the agent CLI logged in (or OpenCode + a local model).",
        "Never runs for pull requests from forks: a self-hosted runner would execute their code on your machine.",
    ],
}
FILES_PROPOSE = {"github": "docs-propose.github.yml", "gitlab": "docs-propose.gitlab-ci.yml"}


def render_propose(forge: str, cfg: dict | None = None) -> str | None:
    """The AI job, only for `ci.target: self-hosted` (H23); None otherwise."""
    cfg = cfg or config()
    if cfg["target"] != "self-hosted":
        return None
    d = {**PR_PROPOSE, "label": cfg.get("propose_label") or PR_PROPOSE["label"]}
    head = "\n".join(f"# {l}" for l in d["doc"])
    if forge == "github":
        return f"""# Camarón — {d['title']}. Generated by `camaron ci github`: edit the definition, not this file.
{head}
# Copy to .github/workflows/{d['id']}.yml in EACH service repo. Variables: DOCS_REPO_URL; optional DOCS_REPO_NAME,
# DOCS_LANG. Secret: DOCS_WRITE_TOKEN (push branches and open PRs on cam-docs). Runner guide: docs/guides/self-hosted-runner.md
name: {d['id']}
on:
  pull_request:
    types: [labeled]
permissions: {{ contents: read, pull-requests: write }}
jobs:
  {d['id']}:
    if: github.event.label.name == '{d['label']}' && github.event.pull_request.head.repo.full_name == github.repository
    runs-on: [{', '.join(cfg['runner_labels'])}]
    env:
      CAMARONES_KIT_REPO: {cfg['kit_repo']}
      CAMARONES_KIT_REF: {cfg['kit_ref']}
      DOCS_REPO_URL: ${{{{ vars.DOCS_REPO_URL }}}}
      DOCS_LANG: ${{{{ vars.DOCS_LANG }}}}
      DOCS_WRITE_TOKEN: ${{{{ secrets.DOCS_WRITE_TOKEN }}}}
      DOCS_CLONE_USER: x-access-token
      GITHUB_TOKEN: ${{{{ github.token }}}}
      PR_NUMBER: ${{{{ github.event.pull_request.number }}}}
      PR_URL: ${{{{ github.event.pull_request.html_url }}}}
      NAME: ${{{{ vars.DOCS_REPO_NAME || github.event.repository.name }}}}
      DOCS_BASE: origin/${{{{ github.base_ref }}}}
    steps:
      - uses: actions/checkout@v4
        with: {{ fetch-depth: 0 }}
      - uses: astral-sh/setup-uv@v6
      - name: {d['title']}
        run: |
          SRC="$GITHUB_WORKSPACE"
{_indent(d['script'], 10)}
      - uses: actions/upload-artifact@v4
        with: {{ name: docs-preview, path: .docs-preview, if-no-files-found: ignore }}
"""
    tags = f"\n  tags: [{', '.join(cfg['runner_tags'])}]" if cfg["runner_tags"] else ""
    script = "SRC=\"$CI_PROJECT_DIR\"\nNAME=\"${DOCS_REPO_NAME:-$CI_PROJECT_NAME}\"\nPR_URL=\"$CI_MERGE_REQUEST_PROJECT_URL/-/merge_requests/$CI_MERGE_REQUEST_IID\"\n" + d["script"]
    return f"""# Camarón — {d['title']}. Generated by `camaron ci gitlab`: edit the definition, not this file.
{head}
# In EACH service repo: include this file from the cam-docs project, or copy the job. Variables: DOCS_REPO_URL,
# DOCS_WRITE_TOKEN (masked: write_repository + api on cam-docs), DOCS_BOT_TOKEN (masked: api on this repo, to comment).
# Runs in the `test` stage on a runner tagged {', '.join(cfg['runner_tags']) or '(no tags)'}. Guide: docs/guides/self-hosted-runner.md

{d['id'].replace('-', ':', 1)}:
  stage: test{tags}
  rules:
    - if: '$CI_PIPELINE_SOURCE == "merge_request_event" && $CI_MERGE_REQUEST_LABELS =~ /(^|,){d['label']}(,|$)/ && $CI_MERGE_REQUEST_SOURCE_PROJECT_ID == $CI_PROJECT_ID'
  allow_failure: true
  variables:
    GIT_DEPTH: "0"
    CAMARONES_KIT_REPO: "{cfg['kit_repo']}"
    CAMARONES_KIT_REF: "{cfg['kit_ref']}"
    DOCS_CLONE_USER: "oauth2"
    DOCS_BASE: "$CI_MERGE_REQUEST_DIFF_BASE_SHA"
  script:
    - |
{_indent(script, 6)}
  artifacts:
    name: docs-preview
    paths: [.docs-preview]
    when: always
    expire_in: 2 weeks
"""
